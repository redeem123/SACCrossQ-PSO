function split = getBenchmarkSplit()
%GETBENCHMARKSPLIT SAC-SAPSO paper benchmark split (von Eschwege & Engelbrecht 2024).
%
%   split = getBenchmarkSplit()
%
%   Returns a struct with fields:
%     train  — cell array of 45 function names (training set)
%     test   — cell array of 7 function names (held-out test set)
%
%   Source: "Soft Actor-Critic Approach to Self-Adaptive Particle Swarm
%   Optimisation," Mathematics 2024, 12, 3481, Appendix A / Table A1.
%   85%/15% train/test split, all 30-dimensional.

    split.train = { ...
        'Ackley1', ...
        'Alpine1', ...
        'Bohachevsky1', ...
        'BonyadiMichalewicz', ...
        'Brown', ...
        'CosineMixture', ...
        'DeflectedCorrugatedSpring', ...
        'Discus', ...
        'DropWave', ...
        'EggCrate', ...
        'EggHolder', ...
        'Elliptic', ...
        'Exponential', ...
        'Giunta', ...
        'HolderTable1', ...
        'Levy3', ...
        'LevyMontalvo2', ...
        'Mishra1', ...
        'Mishra4', ...
        'NeedleEye', ...
        'Norwegian', ...
        'Pathological', ...
        'Penalty1', ...
        'Penalty2', ...
        'Periodic', ...
        'Pinter2', ...
        'Price2', ...
        'Qing', ...
        'Quadric', ...
        'Quintic', ...
        'Rana', ...
        'Rastrigin', ...
        'Ripple25', ...
        'Rosenbrock', ...
        'Salomon', ...
        'Schubert4', ...
        'Schwefel1', ...
        'Sinusoidal', ...
        'StepFunction3', ...
        'Trid', ...
        'Trigonometric', ...
        'Vincent', ...
        'Weierstrass', ...
        'XinSheYang1', ...
        'XinSheYang2', ...
    };

    split.test = { ...
        'CrossLegTable', ...
        'Lanczos3', ...
        'Michalewicz', ...
        'Schaffer4', ...
        'SineEnvelope', ...
        'StretchedVSineWave', ...
        'Wavy', ...
    };

    % --- Validation ---
    assert(numel(split.train) == 45, ...
        'Train set must have exactly 45 functions, got %d', numel(split.train));
    assert(numel(split.test) == 7, ...
        'Test set must have exactly 7 functions, got %d', numel(split.test));
    overlap = intersect(split.train, split.test);
    assert(isempty(overlap), ...
        'Train and test sets must be disjoint. Overlap: %s', strjoin(overlap, ', '));
end
